/*
  Волна 16. Блок «Источники, проверено …» стоял только на трёх страницах сайта
  и в разной вёрстке. Здесь он один на всю сеть страниц site-03: нумерованный
  список первоисточников с датой сверки и, при необходимости, честная строка
  «чего мы НЕ утверждаем». Это защита от протухания фактуры: читатель видит,
  на какую дату сверены сроки и реквизиты актов, а не «когда-то было так».

  Волна приёмки (26.08.2026), две правки — обе про то, что дата сверки была
  видна человеку, но не машине.

  1. Дата обёрнута в <time dateTime="ГГГГ-ММ-ДД">. Раньше «17 августа 2026
     года» было обычным текстом: для читателя понятно, для парсера — ничем не
     отличается от остальной строки. Русская дата разбирается прямо здесь,
     потому что во всём проекте она хранится одной строкой (FACT_CHECK и
     полтора десятка его подневных вариантов в site-data.ts), и заводить рядом
     дублирующую ISO-константу под каждую значило бы завести полтора десятка
     мест, где две даты могут разойтись.

  2. Появился необязательный проп `offer`. На страницах, где показана ставка,
     обязана стоять оговорка «не является публичной офертой» С ДАТОЙ, на
     которую цена верна. Отдельным компонентом это делать не стали: у каждой
     такой страницы уже есть этот блок с той самой датой, и оговорка про цену
     без даты либо с чужой датой — ровно то, чего рубрикатор и не хочет.
*/

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * «12 августа 2026 года» → «2026-08-12». Если строка не разобралась
 * (формат поменяли), возвращаем undefined и <time> просто не ставим —
 * лучше без машиночитаемой даты, чем с выдуманной.
 */
export function isoDate(ru: string): string | undefined {
  const m = ru.match(/(\d{1,2})\s+([а-яё]+)\s+(\d{4})/i);
  if (!m) return undefined;
  const month = MONTHS.indexOf(m[2].toLowerCase());
  if (month < 0) return undefined;
  return `${m[3]}-${String(month + 1).padStart(2, "0")}-${m[1].padStart(2, "0")}`;
}

export interface SourceItem {
  href: string;
  label: string;
}

interface Props {
  date: string;
  items: SourceItem[];
  /** Что сознательно не написано, потому что не подтверждено источником. */
  note?: string;
  /** Ставится на страницах, где показана цена: оговорка про оферту с датой. */
  offer?: boolean;
}

export default function Sources({ date, items, note, offer }: Props) {
  const iso = isoDate(date);
  const stamp = iso ? <time dateTime={iso}>{date}</time> : date;

  return (
    <section className="sources wrap" aria-labelledby="sources-heading">
      <h2 className="sources__title" id="sources-heading">Источники, проверено {stamp}</h2>
      <ol className="sources__list">
        {items.map((s) => (
          <li key={s.href}>
            <a href={s.href} target="_blank" rel="noopener">{s.label}</a>
          </li>
        ))}
      </ol>
      {offer ? (
        <p className="sources__note">
          Прайс на странице верен на {stamp} и не является публичной офертой: итоговая стоимость
          зависит от адреса объекта, доступа на площадку и срока оформления допусков. Обязывающие
          цифры фиксирует коммерческое предложение по вашему объекту.
        </p>
      ) : null}
      {note ? <p className="sources__note">{note}</p> : null}
    </section>
  );
}
